// ─── Helper functions ─────────────────────────────────────────────────────────

const normaliseText = (value) => (typeof value === "string" ? value.trim() : "");

const getPriceNumber = (value) => {
  const parsed = Number(value);
  return Number.isFinite(parsed) ? parsed : 0;
};

export const normalizeProduct = (product) => {
  const source = product || {};
  const categoryValue = normaliseText(source.category || source.categoryName || "Uncategorized");
  const price = getPriceNumber(source.price ?? source.salePrice ?? 0);
  const salePrice = getPriceNumber(source.salePrice ?? 0);
  const stock = getPriceNumber(source.stock ?? source.inventory ?? 0);
  const stockStatus = stock <= 0 ? "Out of Stock" : stock <= 10 ? "Limited Stock" : "In Stock";
  const discountValue = Number(source.discount ?? 0);
  const derivedDiscount =
    Number.isFinite(discountValue) && discountValue > 0
      ? discountValue
      : salePrice > 0 && price > 0
        ? Math.max(0, Math.round(((price - salePrice) / price) * 100))
        : 0;

  const images = Array.isArray(source.images)
    ? source.images.filter(Boolean)
    : source.image
      ? [source.image]
      : [
          "https://images.unsplash.com/photo-1521572163474-6864f9cf17ab?w=800&q=80",
        ];

  const sizes = Array.isArray(source.sizes) && source.sizes.length
    ? source.sizes
    : source.size
      ? [source.size]
      : ["N/A"];

  const colors = Array.isArray(source.colors) && source.colors.length
    ? source.colors
    : source.color
      ? [source.color]
      : ["N/A"];

  const productStatus = String(source.status || "").trim();

  const normalized = {
    ...source,
    id: Number(source.id ?? 0),
    name: source.name || "Untitled Product",
    category: categoryValue || "Uncategorized",
    subcategory: source.subcategory || source.category || categoryValue || "Collection",
    price,
    oldPrice: source.oldPrice ?? (salePrice > 0 && salePrice < price ? price : null),
    discount: derivedDiscount,
    description: source.description || "No description available.",
    images,
    sizes,
    colors,
    stock,
    stockStatus,
    rating: Number(source.rating ?? 4.8) || 4.8,
    reviewCount: Number(source.reviewCount ?? 0) || 0,
    badges: Array.isArray(source.badges) ? source.badges : [],
    isBestSeller: Boolean(source.isBestSeller || source.featured),
    isNew: Boolean(source.isNew || (source.createdAt && Date.now() - new Date(source.createdAt).getTime() < 1000 * 60 * 60 * 24 * 30)),
    isSale: source.salePrice !== undefined && source.salePrice !== null && Number(source.salePrice) < price,
    featured: Boolean(source.featured),
    status: productStatus || (stock <= 0 ? "Out of Stock" : "Active"),
  };

  if (normalized.featured && !normalized.badges.includes("Best Seller")) {
    normalized.badges = ["Best Seller", ...normalized.badges];
  }

  if (normalized.isSale && !normalized.badges.includes("Sale")) {
    normalized.badges = ["Sale", ...normalized.badges];
  }

  return normalized;
};

export const getCustomerVisibleProducts = (productList = []) =>
  (Array.isArray(productList) ? productList : [])
    .map(normalizeProduct)
    .filter((product) => {
      const status = String(product.status || "").toLowerCase();
      return status !== "draft" && status !== "deleted" && status !== "archived";
    });

export const getFeaturedCustomerProducts = (productList = []) =>
  getCustomerVisibleProducts(productList).filter((product) => product.featured === true).slice(0, 8);

export const getNewCustomerProducts = (productList = []) =>
  getCustomerVisibleProducts(productList).filter((product) => product.isNew || product.createdAt).slice(0, 8);

export const getProductById = (id, productList = products) =>
  getCustomerVisibleProducts(productList).find((p) => String(p.id) === String(id));

export const getProductsByCategory = (category, productList = products) => {
  const visibleProducts = getCustomerVisibleProducts(productList);
  return category === "all"
    ? visibleProducts
    : visibleProducts.filter((p) => String(p.category).toLowerCase() === String(category).toLowerCase());
};

export const getBestSellers = (productList = products) =>
  getCustomerVisibleProducts(productList)
    .filter((p) => p.featured || p.isBestSeller)
    .slice(0, 8);

export const getNewArrivals = (productList = products) =>
  getCustomerVisibleProducts(productList)
    .filter((p) => p.isNew)
    .slice(0, 8);

export const getRelatedProducts = (productId, category, productList = products) =>
  getCustomerVisibleProducts(productList)
    .filter((p) => String(p.category).toLowerCase() === String(category).toLowerCase() && String(p.id) !== String(productId))
    .slice(0, 4);

